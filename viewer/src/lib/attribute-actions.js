/// The rows the hover lists for attribute `name`: `[{ action, words, role }]`, `role` being
/// `main` or `support`. Empty for a name with no entry.
export function actionsOf(name) {
  return (ATTRIBUTE_ACTIONS[name] ?? []).map(([action, role]) => ({
    action,
    words: ACTION_WORDS[action] ?? action,
    role,
  }));
}
